import { z } from "zod";
import type { SearchListingDto, SearchListingsRequest, SearchListingsResponse } from "@diploma/contracts/search";

const nullableString = z.string().nullable();
const nullableNumber = z.number().nullable();

export const SearchSortBySchema = z.enum([
  "price_asc",
  "price_desc",
  "published_desc",
  "infrastructure_desc",
]);

export const SearchListingsRequestSchema: z.ZodType<SearchListingsRequest> = z.object({
  query: nullableString.optional(),
  locationId: nullableString.optional(),
  listingType: nullableString.optional(),
  buildingType: nullableString.optional(),
  minPrice: nullableNumber.optional(),
  maxPrice: nullableNumber.optional(),
  minArea: nullableNumber.optional(),
  maxArea: nullableNumber.optional(),
  minInfrastructureScore: nullableNumber.optional(),
  minEducationScore: nullableNumber.optional(),
  minHealthcareScore: nullableNumber.optional(),
  minTransportScore: nullableNumber.optional(),
  minCommerceScore: nullableNumber.optional(),
  minLeisureScore: nullableNumber.optional(),
  minEducationCount: nullableNumber.optional(),
  minHealthcareCount: nullableNumber.optional(),
  minTransportCount: nullableNumber.optional(),
  minCommerceCount: nullableNumber.optional(),
  minLeisureCount: nullableNumber.optional(),
  maxEducationNearestMeters: nullableNumber.optional(),
  maxHealthcareNearestMeters: nullableNumber.optional(),
  maxTransportNearestMeters: nullableNumber.optional(),
  maxCommerceNearestMeters: nullableNumber.optional(),
  maxLeisureNearestMeters: nullableNumber.optional(),
  centerLatitude: nullableNumber.optional(),
  centerLongitude: nullableNumber.optional(),
  radiusMeters: nullableNumber.optional(),
  boundsMinLatitude: nullableNumber.optional(),
  boundsMinLongitude: nullableNumber.optional(),
  boundsMaxLatitude: nullableNumber.optional(),
  boundsMaxLongitude: nullableNumber.optional(),
  sortBy: SearchSortBySchema.nullable().optional(),
  page: z.number(),
  pageSize: z.number(),
});

export const SearchListingDtoSchema: z.ZodType<SearchListingDto> = z.object({
  listingId: z.string(),
  agentId: z.string(),
  title: z.string(),
  description: nullableString,
  addressText: nullableString,
  locationId: nullableString,
  latitude: nullableNumber,
  longitude: nullableNumber,
  listingType: nullableString,
  buildingType: nullableString,
  listingDetailsType: nullableString,
  priceAmount: nullableNumber,
  priceAmountByn: nullableNumber,
  priceAmountUsd: nullableNumber,
  priceCurrency: nullableString,
  areaTotal: z.number(),
  mainMediaUrl: nullableString,
  publishedDate: nullableString,
  infrastructureScore: nullableNumber,
  educationScore: nullableNumber,
  healthcareScore: nullableNumber,
  transportScore: nullableNumber,
  commerceScore: nullableNumber,
  leisureScore: nullableNumber,
  educationCount: nullableNumber,
  healthcareCount: nullableNumber,
  transportCount: nullableNumber,
  commerceCount: nullableNumber,
  leisureCount: nullableNumber,
  educationNearestMeters: nullableNumber,
  healthcareNearestMeters: nullableNumber,
  transportNearestMeters: nullableNumber,
  commerceNearestMeters: nullableNumber,
  leisureNearestMeters: nullableNumber,
  searchFeatures: z.record(z.string(), z.number()),
});

export const SearchListingsResponseSchema: z.ZodType<SearchListingsResponse> = z.object({
  items: z.array(SearchListingDtoSchema),
  page: z.number(),
  pageSize: z.number(),
  totalCount: z.number(),
});
